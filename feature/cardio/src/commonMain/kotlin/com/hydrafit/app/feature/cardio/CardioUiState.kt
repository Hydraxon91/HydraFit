package com.hydrafit.app.feature.cardio

import com.hydrafit.app.core.domain.cardio.CardioActivity
import com.hydrafit.app.core.domain.cardio.CardioActivityType
import com.hydrafit.app.core.domain.cardio.CardioProgress
import com.hydrafit.app.core.domain.cardio.buildCardioProgress
import com.hydrafit.app.core.domain.time.civilFromDays
import com.hydrafit.app.core.domain.time.localCivilToEpochMillis
import com.hydrafit.app.core.domain.time.localEpochDay
import com.hydrafit.app.core.domain.unit.DistanceUnit

/** The explicit chart windows. Only the chart and totals change; history always covers all dates. */
enum class CardioRange(val days: Int) {
    DAYS_28(28),
    DAYS_84(84),
    DAYS_365(365)
}

/** An editor refusal the dialog renders with its own localized guidance. */
enum class CardioEditorError {
    INVALID_START_TIME,
    INVALID_DURATION,
    INVALID_DISTANCE,
    INVALID_NOTE,
    INVALID_ACTIVITY,
    SAVE_FAILED
}

/**
 * The in-progress activity draft. It exists only while the editor is open and never persists on its
 * own, so Cancel discards it without writing.
 *
 * [initialStartText] and [initialDistanceText] are the exact text the editor opened with. An untouched
 * distance field compares equal to its initial text, which lets an unchanged edit reuse the stored
 * whole metres rather than round-tripping them through a rounded display value.
 */
data class CardioEditorState(
    /** The stored id being edited, or null for a new activity. */
    val previousId: Long? = null,
    /** The stored identity, preserved across an edit and generated by the use case for a new row. */
    val identity: String = "",
    val initialStartText: String,
    val startText: String = initialStartText,
    val type: CardioActivityType,
    val minutesText: String = "",
    val secondsText: String = "",
    val initialDistanceText: String = "",
    val distanceText: String = initialDistanceText,
    val noteText: String = "",
    val error: CardioEditorError? = null,
    val pendingDelete: Boolean = false
)

/**
 * Presentation state for the standalone Cardio destination.
 *
 * Activities are canonical records; the display distance unit is applied only at the edges, so
 * switching it never writes to the repository. [progress] is rebuilt from the selected window and the
 * current local offset, never cached across a range change.
 */
data class CardioUiState(
    val utcOffsetMillis: Long = 0L,
    val distanceUnit: DistanceUnit = DistanceUnit.METERS,
    val range: CardioRange = CardioRange.DAYS_28,
    val todayLocalEpochDay: Long = 0L,
    val loading: Boolean = true,
    val loadFailed: Boolean = false,
    val activities: List<CardioActivity> = emptyList(),
    val editor: CardioEditorState? = null,
    val submitting: Boolean = false
) {
    /** Newest first, with the local id breaking a same-instant tie so the order is stable. */
    val sortedActivities: List<CardioActivity>
        get() = activities.sortedWith(
            compareByDescending<CardioActivity> { it.startedAtMillis }.thenByDescending { it.id }
        )

    /** No activity has ever been recorded, distinct from "none in this range" and a failed load. */
    val isEmpty: Boolean
        get() = !loading && !loadFailed && activities.isEmpty()

    /** The inclusive last day of the selected window: today in the re-sampled local offset. */
    val chartDayTo: Long
        get() = todayLocalEpochDay

    /** The inclusive first day of the selected window, [CardioRange.days] long ending on [chartDayTo]. */
    val chartDayFrom: Long
        get() = todayLocalEpochDay - (range.days - 1L)

    /** Totals and daily values for the selected window, computed from the shared domain aggregate. */
    val progress: CardioProgress
        get() = buildCardioProgress(
            activities = activities,
            fromEpochDay = chartDayFrom,
            throughEpochDay = chartDayTo,
            utcOffsetMillis = utcOffsetMillis
        )

    /** The selected window recorded no activity, distinct from an entirely empty history. */
    val rangeIsEmpty: Boolean
        get() = !loading && !loadFailed && progress.totalsByType.isEmpty()
}

private val CARDIO_START_TIME = Regex("""(\d{4})-(\d{2})-(\d{2}) (\d{2}):(\d{2})""")

/**
 * Parses a `YYYY-MM-DD HH:mm` local start time into a UTC epoch-millis instant under the supplied
 * fixed offset, or returns null when the text is not that exact shape or names an impossible day.
 *
 * The civil conversion is the shared `:core/domain` algorithm. It normalises an impossible day such
 * as `2024-02-30` forward, so the parsed instant is round-tripped back through [localEpochDay] and
 * [civilFromDays] and rejected when the day no longer matches the input.
 */
internal fun parseCardioStartTime(text: String, utcOffsetMillis: Long): Long? {
    val match = CARDIO_START_TIME.matchEntire(text.trim()) ?: return null
    val year = match.groupValues[1].toInt()
    val month = match.groupValues[2].toInt()
    val day = match.groupValues[3].toInt()
    val hour = match.groupValues[4].toInt()
    val minute = match.groupValues[5].toInt()
    if (month !in 1..12) return null
    if (hour !in 0..23 || minute !in 0..59) return null
    val millis = localCivilToEpochMillis(year, month, day, hour, minute, utcOffsetMillis)
    val (parsedYear, parsedMonth, parsedDay) =
        civilFromDays(localEpochDay(millis, utcOffsetMillis))
    if (parsedYear != year || parsedMonth != month || parsedDay != day) return null
    return millis
}
